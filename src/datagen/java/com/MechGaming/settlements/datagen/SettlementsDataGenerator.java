package com.MechGaming.settlements.datagen;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/** Deterministic Java 8 DataGen for Minecraft 1.12.2's legacy resource layouts. */
public final class SettlementsDataGenerator {
    private final Map<String, String> resources = new LinkedHashMap<>();
    private SettlementsDataGenerator(String version) throws IOException {
        json("mcmod.info", Arrays.asList(object(
            "modid", "settlements", "name", "Settlements",
            "description", "Player-founded settlements, configurable claims and zones, NPC housing, raids, blueprints and consensual wars.",
            "version", version, "mcversion", "1.12.2", "authorList", Arrays.asList("MechGaming"),
            "credits", "Built with Minecraft Forge. Flag model by MechGaming; Minecraft textures used for placeholders.",
            "url", "", "updateUrl", "", "logoFile", "", "screenshots", new ArrayList<>(), "dependencies", new ArrayList<>())));
        json("pack.mcmeta", object("pack", object("description", "Settlements resources by MechGaming", "pack_format", 3)));

        importFlagModel();
        json("assets/settlements/blockstates/settlement_flag.json", object("variants", object("normal", object("model", "settlements:settlement_flag"))));
        json("assets/settlements/models/item/settlement_flag.json", object("parent", "settlements:block/settlement_flag"));
        json("assets/settlements/models/item/dev_tool.json", object("parent", "minecraft:item/generated", "textures", object("layer0", "minecraft:items/blaze_rod")));
        json("assets/settlements/recipes/settlement_flag.json", object(
            "type", "minecraft:crafting_shaped", "group", "settlements",
            "pattern", Arrays.asList("WW ", "WWS", "  S"),
            "key", object("W", object("item", "minecraft:wool", "data", 32767), "S", object("item", "minecraft:stick")),
            "result", object("item", "settlements:settlement_flag", "count", 1)));

        String language = "# Generated by SettlementsDataGenerator. Add overrides in src/main/resources.\n"
            + "tile.settlements.settlement_flag.name=Settlement Flag\n"
            + "item.settlements.dev_tool.name=Settlement Developer Tool\n"
            + "tile.settlement_flag.name=Settlement Flag\n"
            + "item.dev_tool.name=Settlement Developer Tool\n"
            + "entity.settlements.settler.name=Settler\n"
            + "itemGroup.settlements=Settlements\n"
            + "key.categories.settlements=Settlements\n"
            + "key.settlements.planner=Settlements\n"
            + "key.settlements.boundaries=Show Settlement Boundaries\n"
            + "settlements.key.planner=Settlements\n"
            + "settlements.key.boundaries=Show Settlement Boundaries\n";
        resources.put("assets/settlements/lang/en_us.lang", language);

        json("settlements/default_npc.json", object(
            "id", "settler", "name", "Settler", "minRoomVolume", 8, "maxRoomVolume", 512,
            "requiredBlocks", object("minecraft:bed", 1, "minecraft:chest", 1, "minecraft:wooden_door", 1),
            "trades", Arrays.asList(object("buy", "minecraft:emerald", "buyCount", 1, "sell", "minecraft:bread", "sellCount", 3, "uses", 12)),
            "structureBlocks", new ArrayList<>()));

    }

    /** Convert the artist's export to legacy resource names without changing geometry or UVs. */
    private void importFlagModel() throws IOException {
        InputStream source = SettlementsDataGenerator.class.getResourceAsStream("/models/flag.json");
        if (source == null) throw new IOException("Missing artist model export: models/flag.json");
        JsonObject model;
        try (InputStreamReader reader = new InputStreamReader(source, StandardCharsets.UTF_8)) {
            model = new JsonParser().parse(reader).getAsJsonObject();
        }
        // The export's parent points back to itself; the supplied elements are standalone.
        model.remove("parent");
        model.remove("format_version");
        model.getAsJsonObject("display").remove("on_shelf"); // Not a Minecraft 1.12 display context.
        JsonObject textures = model.getAsJsonObject("textures");
        textures.addProperty("1", "minecraft:blocks/log_oak");
        textures.addProperty("2", "settlements:blocks/flag_fabric");
        textures.addProperty("particle", "settlements:blocks/flag_fabric");
        resources.put("assets/settlements/models/block/settlement_flag.json",
            new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(model) + "\n");
    }

    public static void main(String[] args) throws IOException {
        if (args.length < 2) throw new IllegalArgumentException("Usage: SettlementsDataGenerator <output> <version> [--verify]");
        SettlementsDataGenerator generator = new SettlementsDataGenerator(args[1]);
        boolean verify = args.length > 2 && "--verify".equals(args[2]);
        Path root = Paths.get(args[0]).toAbsolutePath().normalize();
        int changed = 0;
        for (Map.Entry<String, String> entry : generator.resources.entrySet()) {
            Path path = root.resolve(entry.getKey()).normalize();
            if (!path.startsWith(root)) throw new IOException("Generated path escaped resource root");
            byte[] expected = entry.getValue().getBytes(StandardCharsets.UTF_8);
            boolean matches = Files.isRegularFile(path) && Arrays.equals(Files.readAllBytes(path), expected);
            if (verify && !matches) throw new IOException("Generated resource differs: " + entry.getKey());
            if (!verify && !matches) {
                Files.createDirectories(path.getParent());
                Files.write(path, expected);
                changed++;
            }
        }
        System.out.println((verify ? "Verified " : "Generated ") + generator.resources.size() + " resources; " + changed + " changed.");
    }

    private void json(String path, Object value) { resources.put(path, encode(value, 0) + "\n"); }
    private static Map<String, Object> object(Object... entries) {
        if ((entries.length & 1) != 0) throw new IllegalArgumentException("Object entries must be key/value pairs");
        Map<String, Object> map = new LinkedHashMap<>();
        for (int i = 0; i < entries.length; i += 2) map.put((String) entries[i], entries[i + 1]);
        return map;
    }
    private static String encode(Object value, int depth) {
        if (value == null) return "null";
        if (value instanceof String) return quote((String) value);
        if (value instanceof Number || value instanceof Boolean) return value.toString();
        String indent = repeat("  ", depth), childIndent = indent + "  ";
        if (value instanceof Map) {
            Map<?, ?> map = (Map<?, ?>) value;
            if (map.isEmpty()) return "{}";
            List<String> entries = new ArrayList<>();
            for (Map.Entry<?, ?> entry : map.entrySet()) entries.add(childIndent + quote(entry.getKey().toString()) + ": " + encode(entry.getValue(), depth + 1));
            return "{\n" + String.join(",\n", entries) + "\n" + indent + "}";
        }
        if (value instanceof Iterable) {
            List<String> values = new ArrayList<>();
            for (Object element : (Iterable<?>) value) values.add(childIndent + encode(element, depth + 1));
            return values.isEmpty() ? "[]" : "[\n" + String.join(",\n", values) + "\n" + indent + "]";
        }
        throw new IllegalArgumentException("Unsupported JSON value: " + value.getClass().getName());
    }
    private static String repeat(String value, int count) {
        StringBuilder result = new StringBuilder();
        for (int i = 0; i < count; i++) result.append(value);
        return result.toString();
    }
    private static String quote(String value) {
        StringBuilder result = new StringBuilder("\"");
        for (char c : value.toCharArray()) {
            switch (c) {
                case '"': result.append("\\\""); break;
                case '\\': result.append("\\\\"); break;
                case '\n': result.append("\\n"); break;
                case '\r': result.append("\\r"); break;
                case '\t': result.append("\\t"); break;
                default:
                    if (c < 32) result.append(String.format("\\u%04x", (int) c)); else result.append(c);
            }
        }
        return result.append('"').toString();
    }
}
